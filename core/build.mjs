// rubiks-head/core/build.mjs — rebuild the client from readable source.
//   node build.mjs
//
// Output layout:
//   out/index.html            the single page
//   out/engine-test.html      transport/abi debug harness
//   out/webclient/*.js        one bundle per BUNDLES entry (parts concatenated
//                           in sorted order — shared/api-url.js is prepended
//                           where a bundle must be self-contained, e.g. the
//                           worker-loaded WebClient.js)
//   out/webclient/*           wasm + metadata staged verbatim from staging/
//   server/api-ids.json       domainId -> domain (regenerated every build)
//   core/js/_ids.js           domain -> domainId (generated, do not edit)
import fs from 'fs';
import path from 'path';
import crypto from 'crypto';

const OUT = path.resolve('..', 'out');
const WC = path.join(OUT, 'webclient');
const JS = './js';
const ST = './staging';

// ── 0. opaque domain ids + upstream host config ─────────────────────────────
const seed = JSON.parse(fs.readFileSync('./_ids-seed.json', 'utf8'));
// upstream hosts come from ../server/cnfg.json "upstream" (gitignored — no
// upstream literals live in the source tree). Falls back to cnfg.example.json
// so a fresh clone still builds.
const readJson = p => { try { return JSON.parse(fs.readFileSync(p, 'utf8')); } catch { return null } };
const UPSTREAM = readJson('../server/cnfg.json')?.upstream ||
                 readJson('../server/cnfg.example.json')?.upstream || {};
if (!UPSTREAM.domain || !UPSTREAM.cdn)
  console.warn('[build] no upstream config (server/cnfg.json "upstream") — see server/cnfg.example.json');
fs.writeFileSync(path.join(JS, '_upstream.js'),
  `// GENERATED by build.mjs — upstream host config from server/cnfg.json. Do not edit.\n` +
  `globalThis.UPSTREAM=${JSON.stringify(UPSTREAM)};\n`);
// deterministic ids: sha256(domain)[:5] — server computes the same map at boot
// (server/index.js), so client and server can never desync across builds.
const tok = d => crypto.createHash('sha256').update(d).digest('hex').slice(0, 5);
const API = {}, IDS = {};
for (const domain of seed.services) { const id = tok(domain); API[domain] = id; IDS[id] = domain; }
fs.writeFileSync(path.join(JS, '_ids.js'),
  `// GENERATED by build.mjs — opaque domain ids (regen each build). Do not edit.\n` +
  `globalThis.API=${JSON.stringify(API)};\n`);
// server/map.json: id -> {domain, host, args[]} — generated WITH the ids so the
// two never desync. args = allowed path prefixes; widen as new paths appear.
const RBXCDN = /^(c\d+|t\d+|tr|s\d+|setup|static|cdn|asset|web|e\d+|m\d+)$/;
const HOST_OVERRIDE = UPSTREAM.domain ? {
  universes: `apis.${UPSTREAM.domain}`,
  fts: `fts.${UPSTREAM.cdn}`,
  'ephemeralcounters.api': `ephemeralcounters.api.${UPSTREAM.domain}`,
} : {};
const KNOWN_ARGS = {
  gamejoin: ['/v1/join-game'],
  assetdelivery: ['/v1/asset', '/v1/assets', '/v2/asset'],
  users: ['/v1/users'], universes: ['/v1/universes', '/v2/universes'],
  games: ['/v1/games', '/v2/games'],
  economy: ['/v1/assets', '/v2/assets', '/v1/purchases'],
  thumbnails: ['/v1/batch', '/v1/thumbnail'],
  gameinternationalization: ['/v1/name', '/v2/name', '/v1/user-localization-settings'],
  apis: ['/'],
  ecsv2: ['/client', '/timespent'], 'ephemeralcounters.api': ['/v1.0'], cdn: ['/'], fts: ['/'],
};
const map = {};
for (const id in IDS) {
  const d = IDS[id];
  map[id] = {
    domain: d,
    host: HOST_OVERRIDE[d] || (d.includes('.') ? d : (RBXCDN.test(d) ? `${d}.${UPSTREAM.cdn || ''}` : `${d}.${UPSTREAM.domain || ''}`)),
    args: KNOWN_ARGS[d] || ['/'],
  };
}
fs.writeFileSync('../server/map.json', JSON.stringify(map, null, 1));
console.log(`[build] api-ids: ${seed.services.length} domains -> js/_ids.js + server/map.json`);

// ── 1. bundles: name -> ordered list of source files ─────────────────────────
// Order is explicit (no filename prefixes needed); shared/api-url.js is
// prepended to every bundle that must be self-contained (workers load
// WebClient.js alone — no page script tags there).
const SHARED = ['js/_upstream.js', 'js/shared/api-url.js'];
const BUNDLES = {
  'consolelog.js':           ['js/consolelog.js'],
  'i18n.js':                 ['js/i18n.js'],
  '_ids.js':                 ['js/_ids.js'],
  'api-url.js':              [...SHARED],
  'WasmLoader.js':           [...SHARED,
    'js/loader/head.js', 'js/loader/environments.js', 'js/loader/user-channel.js',
    'js/loader/engine-version.js', 'js/loader/boot.js'],
  'WasmPlayer.js':           [...SHARED,
    'js/player/head.js', 'js/player/env.js', 'js/player/flags.js',
    'js/player/host-info.js', 'js/player/locale.js', 'js/player/loading-screen.js',
    'js/player/tab-lock.js', 'js/player/engine-launch.js', 'js/player/exit.js',
    'js/player/stats-overlay.js', 'js/player/boot.js'],
  'WebClient.js':            [...SHARED, 'js/consolelog.js',
    'js/engine/webclient/relay-config.js', 'js/engine/webclient/ws-transport.js',
    'js/engine/webclient/dns-shim.js', 'js/engine/webclient/prelude.js',
    'js/engine/webclient/create-web-client.js', 'js/engine/webclient/xhr.js',
    'js/engine/webclient/glue.js', 'js/engine/webclient/tail.js'],
  'driver.js':               ['js/engine/transport/socket-pump.js'],
  'stub.js':                 ['js/engine/worker/stub.js'],
  'audio-processor-fast.js': ['js/engine/audio/processor.js'],
};

fs.mkdirSync(WC, { recursive: true });
for (const [out, parts] of Object.entries(BUNDLES)) {
  const files = [];
  for (const p of parts) {
    if (fs.statSync(p).isDirectory())
      for (const f of fs.readdirSync(p).filter(x => x.endsWith('.js')).sort())
        files.push(path.join(p, f));
    else files.push(p);
  }
  fs.writeFileSync(path.join(WC, out), files.map(f => fs.readFileSync(f, 'utf8')).join('\n'));
  console.log(`[build] ${out} <- ${files.length} files`);
}

// ── 2. stage wasm + engine assets verbatim (files AND asset dirs) ───────────
// staging/ is populated from an engine dump — see scripts/fetch-engine.mjs
// and core/sync-staging.mjs. It is absent (or wasm-less) in a clean tree.
if (fs.existsSync(ST)) {
  for (const f of fs.readdirSync(ST)) {
    const src = path.join(ST, f);
    if (fs.statSync(src).isDirectory()) fs.cpSync(src, path.join(WC, f), { recursive: true });
    else if (/\.(wasm|json|pack|rbxm|ttf|otf|tex|png|jpg)$/i.test(f)) fs.copyFileSync(src, path.join(WC, f));
  }
  console.log('[build] staged wasm/assets -> out/webclient');
} else {
  console.warn('[build] core/staging missing — engine assets not staged (run scripts/fetch-engine.mjs)');
}

// ── 3. pages + root assets ──────────────────────────────────────────────────
fs.copyFileSync('./index.html', path.join(OUT, 'index.html'));
if (fs.existsSync('./engine-test.html'))
  fs.copyFileSync('./engine-test.html', path.join(OUT, 'engine-test.html'));
for (const f of fs.readdirSync('.'))
  if (/\.(svg|png|ico)$/i.test(f)) fs.copyFileSync(f, path.join(OUT, f));
console.log('[build] index.html + engine-test.html -> out/');
console.log('[build] done ->', OUT);
